def _write_tool(slug, js):
    js = "'use strict';\n/* Generated by make-ask.py from the tool's own page. Do not edit; edit make-tools.py. */\n" + js.strip() + '\n'
    h = _ahl.sha1(js.encode()).hexdigest()[:8]
    name = f'tools/{slug}.{h}.js'
    open(name, 'w').write(js)
    _TOOLFILES[slug] = '/' + name

