#                            (calculators and question tools), or cut from the hand-written Pipeline and
#                            Deal pages. Ask QuotaBird loads one of these on demand. One source, no copies.
#   ask-quotabird/, meeting-prep/, account-plan/, update-upward/   the pages
#   lambda/quotabird-catalog.mjs   the tool list the Lambda routes against (deploy it with the Lambda)
#
# The AI never does arithmetic. The Lambda (lambda/quotabird.mjs) picks the tool and pulls the numbers
# out of what the person typed; this page runs the tool's own compute(); the Lambda then explains the
# result it was handed. See HANDOFF.md, "Ask QuotaBird".
